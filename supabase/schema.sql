-- ZYLO V1 whole-house schema. Safe for the existing project table: it does not drop it.

create extension if not exists pgcrypto;

create table if not exists public.homes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  overall_style text default 'Modern',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.spaces (
  id uuid primary key default gen_random_uuid(),
  home_id uuid not null references public.homes(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  type text not null,
  target_style text,
  status text not null default 'not designed',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.designs (
  id uuid primary key default gen_random_uuid(),
  home_id uuid not null references public.homes(id) on delete cascade,
  space_id uuid not null references public.spaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  image_path text,
  generated_image_path text,
  detected_style text,
  confidence double precision,
  target_style text,
  prompt text,
  budget_inr numeric default 0,
  recommendations jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.usage_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null,
  units integer not null default 1,
  metadata jsonb,
  created_at timestamptz not null default now()
);

alter table public.homes enable row level security;
alter table public.spaces enable row level security;
alter table public.designs enable row level security;
alter table public.usage_events enable row level security;

grant select, insert, update, delete on public.homes, public.spaces, public.designs to authenticated;
grant select, insert on public.usage_events to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- Recreate policies idempotently.
