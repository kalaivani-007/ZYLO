-- Private room image bucket.
insert into storage.buckets (id, name, public)
values ('room-images', 'room-images', false)
on conflict (id) do update set public = false;

drop policy if exists "zylo_room_upload" on storage.objects;
drop policy if exists "zylo_room_select" on storage.objects;
drop policy if exists "zylo_room_update" on storage.objects;
drop policy if exists "zylo_room_delete" on storage.objects;

create policy "zylo_room_upload" on storage.objects for insert to authenticated
with check (bucket_id='room-images' and (storage.foldername(name))[1]=auth.uid()::text);
create policy "zylo_room_select" on storage.objects for select to authenticated
using (bucket_id='room-images' and (storage.foldername(name))[1]=auth.uid()::text);
create policy "zylo_room_update" on storage.objects for update to authenticated
using (bucket_id='room-images' and (storage.foldername(name))[1]=auth.uid()::text)
with check (bucket_id='room-images' and (storage.foldername(name))[1]=auth.uid()::text);
create policy "zylo_room_delete" on storage.objects for delete to authenticated
using (bucket_id='room-images' and (storage.foldername(name))[1]=auth.uid()::text);
